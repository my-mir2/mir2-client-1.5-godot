    private static void RegisterAlias(string aliasName, string canonicalName)
    {
        if (ItemsByName.TryGetValue(canonicalName, out var entry))
        {
            ItemsByName[aliasName] = entry;
        }
    }

    private static void Register(StdItemEntry e)
    {
        ItemsByIdx[e.Idx] = e;
        if (!ItemsByName.ContainsKey(e.Name))
            ItemsByName[e.Name] = e;
    }

    public static int ResolveLooks(string itemName, int defaultLooks = 1)
    {
        if (string.IsNullOrEmpty(itemName)) return defaultLooks;
        if (ItemsByName.TryGetValue(itemName, out var entry)) return entry.Looks;
        return defaultLooks;
    }

    /// <summary>
    /// 依据官方 1.4/1.5 StdItems.DB 规范 StdMode 属性权威判定装备槽位 (零猜测、纯数据驱动)
    /// 0: 衣服 (StdMode 10, 11)
    /// 1: 武器 (StdMode 5, 6)
    /// 2: 照明/护符/毒药/右持物 (StdMode 25, 30)
    /// 3: 项链 (StdMode 19, 20, 21)
    /// 4: 头盔 (StdMode 15)
    /// 5: 手镯 (StdMode 24, 26) -> 默认左手镯
    /// 7: 戒指 (StdMode 22, 23) -> 默认左戒指
    /// -1: 非装备或未识别物品
    /// </summary>
    public static int ResolveEquipSlot(string itemName)
    {
        if (string.IsNullOrEmpty(itemName)) return -1;
        if (!ItemsByName.TryGetValue(itemName, out var entry)) return -1;

        return entry.StdMode switch
        {
            10 or 11 => 0, // Dress (衣服)
            5 or 6 => 1,   // Weapon (武器)
            25 or 30 => 2, // Lighting/Amulet/Poison (照明/护身符/毒药)
            19 or 20 or 21 => 3, // Necklace (项链)
            15 => 4,       // Helmet (头盔)
            24 or 26 => 5, // Armring (手镯)
            22 or 23 => 7, // Ring (戒指)
            _ => -1
        };
    }
