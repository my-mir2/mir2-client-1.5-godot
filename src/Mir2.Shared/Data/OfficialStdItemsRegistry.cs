    private static void RegisterAlias(string aliasName, string canonicalName)
    {
        if (ItemsByName.TryGetValue(canonicalName, out var entry))
        {
            ItemsByName[aliasName] = entry;
        }
    }

    private static void Register(StdItemEntry e)
    {
        ItemsByIdx[e.Idx] = e;
        if (!ItemsByName.ContainsKey(e.Name))
            ItemsByName[e.Name] = e;
    }

    public static int ResolveLooks(string itemName, int defaultLooks = 1)
    {
        if (string.IsNullOrEmpty(itemName)) return defaultLooks;
        if (ItemsByName.TryGetValue(itemName, out var entry)) return entry.Looks;
        return defaultLooks;
    }
